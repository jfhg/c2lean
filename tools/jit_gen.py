#!/usr/bin/env python3
"""jit_gen.py — turn MCJIT ground truth into Lean theorems.

Runs the real LLVM (MCJIT) on a corpus of inputs, then EMITS
examples/build/C2Lean/McjitCheck.lean: one `native_decide` theorem per case, stating
that OUR Lean machine produces the value the real machine produced.

The cross-check becomes a build gate: if c2lean.py mistranslates or
LlSemantics models an instruction wrongly, `lake build` fails — no
human eyeballs required.
"""
import ctypes, os, subprocess, tempfile
from llvmlite import binding as llvm

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))

llvm.initialize_all_targets(); llvm.initialize_native_asmprinter()
tm = llvm.Target.from_default_triple().create_target_machine()
_tmp = tempfile.TemporaryDirectory(prefix="jit-")
def _ll(c):   # compile C -> ephemeral IR (C is the committed input)
    c = os.path.join(ROOT, c)
    out = os.path.join(_tmp.name, os.path.basename(c)[:-2] + ".ll")
    subprocess.run(["clang", "-O0", "-emit-llvm", "-S", c, "-o", out],
                   check=True)
    return out
mods = [llvm.parse_assembly(open(_ll(c)).read()) for c in
        ("examples/fact.c", "examples/twice.c", "examples/qsort.c",
         "examples/localarr.c")]
for m in mods: m.verify()
ee = llvm.create_mcjit_compiler(mods[0], tm)
for m in mods[1:]: ee.add_module(m)
ee.finalize_object(); ee.run_static_constructors()

U = lambda v: v & 0xFFFFFFFF   # int32 (signed view) -> Nat (unsigned, our w32)
out = []

fact = ctypes.CFUNCTYPE(ctypes.c_int32, ctypes.c_int32)(ee.get_function_address("fact"))
for n in range(13):
    out.append(f"theorem mc_fact_{n} : (runModule factM \"fact\" [{n}] 200 Mem.empty).val?"
               f" = some {U(fact(n))} := by native_decide")

addtwice = ctypes.CFUNCTYPE(ctypes.c_int32, ctypes.c_int32, ctypes.c_int32)(
    ee.get_function_address("addtwice"))
for a, b in [(0, 0), (3, 4), (100, 200), (1000000, 1)]:
    out.append(f"theorem mc_addtwice_{a}_{b} :"
               f" (runModule twiceM \"addtwice\" [{a}, {b}] 40 Mem.empty).val?"
               f" = some {U(addtwice(a, b))} := by native_decide")

la = ctypes.CFUNCTYPE(ctypes.c_int32, ctypes.c_int32)(ee.get_function_address("localarr"))
for n in range(8):
    out.append(f"theorem mc_localarr_{n} :"
               f" (runModule localarrM \"localarr\" [{n}] 1000 Mem.empty).val?"
               f" = some {U(la(n))} := by native_decide")

qs = ctypes.CFUNCTYPE(None, ctypes.POINTER(ctypes.c_int32), ctypes.c_int32, ctypes.c_int32)(
    ee.get_function_address("quickSort"))
CASES = [[5, 3, 8, 1, 2], [42], [3, 3, 3], [9, 7, 5, 3, 1, 8, 6, 4, 2, 0], [1, 5], [2, 1]]
for i, arr in enumerate(CASES):
    buf = (ctypes.c_int32 * len(arr))(*arr)
    qs(buf, 0, len(arr) - 1)
    res = ", ".join(str(U(v)) for v in buf)
    out.append(f"theorem mc_qsort_{i} : carrGet (cfinMem"
               f" (runModule qsortM \"quickSort\" [0, 0, {len(arr)-1}] 8000"
               f" (carrMem [{', '.join(map(str, arr))}]))) {len(arr)}"
               f" = [{res}] := by native_decide")

import os
os.makedirs(os.path.join(ROOT, "examples/build/C2Lean"), exist_ok=True)
with open(os.path.join(ROOT, "examples/build/C2Lean/McjitCheck.lean"), "w") as fh:
    fh.write("""-- GENERATED by jit_gen.py — MCJIT ground truth, do not edit.
-- Each theorem asserts: the Lean machine returns what REAL x86-64
-- machine code (compiled by LLVM from the same C) returned.
-- A mistranslation makes `lake build` fail.
import Proofs.Calls
import C2Lean.Programs

namespace C2Lean
open Ll

""")
    fh.write("\n\n".join(out) + "\n\nend C2Lean\n")
print(f"jit_gen: wrote examples/build/C2Lean/McjitCheck.lean ({len(out)} ground-truth theorems)")
